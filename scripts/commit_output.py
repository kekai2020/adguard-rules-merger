#!/usr/bin/env python3
"""Commit the regenerated output/ onto the latest origin/main and push.

Used by .github/workflows/merge.yml ("Commit subscription files"). The rule
files under output/ are fully regenerated by the "Run merge" step on every run,
so there is nothing to rebase: we build directly on top of the latest
origin/main.

History: an earlier revision used ``git pull --rebase origin main`` here. Two
push-triggered merge runs 18 minutes apart raced and the second one's rebase
collided with the different output/ the first run had already pushed, failing
the job after 3 retries. Rebasing a fully-generated directory is meaningless and
conflict-prone, so this script soft-resets onto origin/main instead (which keeps
the freshly generated files) and re-stages output/ — a conflict is not possible.
A workflow-lint test (tests/test_ci_commit_step.py) asserts ``pull --rebase``
never reappears in that step.

The git sequence lives in :func:`commit_output` with an injectable ``run``
callable so the test-suite can exercise the success / no-change / retry / all-
attempts-exhausted paths against a fake git without touching a real repo.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import time
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Git runner signature: run(args) -> return code. stderr/stdout are captured by
# the real runner; the fake runner in tests returns whatever it wants.
Run = Callable[[list[str]], int]
# Sleep callable (patched in tests so retries are instant).
Sleeper = Callable[[float], None]


class NoChanges(Exception):
    """Raised when output/ is byte-identical to origin/main (nothing to commit)."""


def default_run(args: list[str]) -> int:
    """Real git runner: stream output through, return the exit code."""
    return subprocess.run(args).returncode


def commit_output(
    *,
    output_dir: str,
    message: str,
    remote: str = "origin",
    branch: str = "main",
    attempts: int = 3,
    sleep: Sleeper = time.sleep,
    run: Run = default_run,
    output: Callable[[str], None] = print,
) -> bool:
    """Rebuild output/ on top of origin/<branch> and push. Returns True on success.

    Raises :class:`NoChanges` when output/ is byte-identical to origin/<branch>
    (nothing to commit) — the caller treats that as success.
    """
    for attempt in range(1, attempts + 1):
        output(f"--- attempt {attempt}: sync onto {remote}/{branch} ---")
        if run(["git", "fetch", remote, branch]) != 0:
            output(f"fetch {remote} {branch} failed")
            sleep(5)
            continue
        # Soft reset: move the branch pointer to origin/main but KEEP the working
        # tree and index (the freshly generated output/). Nothing is replayed, so
        # no conflict can arise.
        if run(["git", "reset", "--soft", f"{remote}/{branch}"]) != 0:
            output("soft reset failed")
            sleep(5)
            continue

        # Two-step stage: clear the stale index entries under output/, then force-
        # add whatever exists now. This correctly stages additions AND deletions.
        run(["git", "rm", "-r", "--cached", output_dir])  # tolerated if untracked
        if run(["git", "add", "-f", output_dir]) != 0:
            output(f"git add {output_dir} failed")
            sleep(5)
            continue

        if run(["git", "diff", "--cached", "--quiet"]) == 0:
            output("No changes detected — skipping commit")
            raise NoChanges

        if run(["git", "commit", "-m", message]) != 0:
            output("git commit failed")
            sleep(5)
            continue
        if run(["git", "push", remote, branch]) == 0:
            output(f"Push successful (attempt {attempt})")
            return True
        output(f"push failed on attempt {attempt} (origin moved?), retrying...")
        sleep(5)

    output(f"ERROR: Push failed after {attempts} attempts")
    return False


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", default="output")
    ap.add_argument("--remote", default="origin")
    ap.add_argument("--branch", default="main")
    ap.add_argument("--attempts", type=int, default=3)
    ap.add_argument(
        "--message",
        default=None,
        help="commit message; default summarises output/stats.json",
    )
    args = ap.parse_args(argv)

    message = args.message
    if message is None:
        message = _default_message(Path(args.out_dir))
    try:
        committed = commit_output(
            output_dir=args.out_dir,
            message=message,
            remote=args.remote,
            branch=args.branch,
            attempts=args.attempts,
        )
        rc = 0 if committed else 1
    except NoChanges:
        committed = False
        rc = 0
    # The workflow's Summary step reads steps.commit.outputs.committed, which is
    # fed by $GITHUB_OUTPUT. No-op outside Actions (env var unset).
    _write_github_output(committed)
    return rc


def _write_github_output(committed: bool) -> None:
    """Append committed=true|false to $GITHUB_OUTPUT when running in Actions."""
    import os

    path = os.environ.get("GITHUB_OUTPUT")
    if not path:
        return
    try:
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(f"committed={'true' if committed else 'false'}\n")
    except OSError:
        pass


def _default_message(out_dir: Path) -> str:
    """Summarise output/stats.json into the conventional auto-merge message."""
    import json

    summary = ""
    stats_file = out_dir / "stats.json"
    try:
        s = json.loads(stats_file.read_text(encoding="utf-8"))
        summary = f"[block={s['rules']['block']:,} allow={s['rules']['allow']:,}]"
    except (OSError, json.JSONDecodeError, KeyError, TypeError):
        summary = ""
    import datetime

    stamp = datetime.datetime.now(datetime.UTC).strftime("%Y-%m-%d %H:%M UTC")
    return f"Auto-merge: update rules {summary} {stamp}".replace("  ", " ").strip()


if __name__ == "__main__":
    sys.exit(main())
